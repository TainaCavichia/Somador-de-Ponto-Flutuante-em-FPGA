library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity tb_fp_adder is
end tb_fp_adder;

architecture sim of tb_fp_adder is

    ------------------------------------------------------------------
    -- Entradas
    ------------------------------------------------------------------
    signal sign1, sign2 : std_logic;
    signal exp1, exp2   : std_logic_vector(3 downto 0);
    signal frac1, frac2 : std_logic_vector(7 downto 0);

    ------------------------------------------------------------------
    -- Saídas
    ------------------------------------------------------------------
    signal sign_out : std_logic;
    signal exp_out  : std_logic_vector(3 downto 0);
    signal frac_out : std_logic_vector(7 downto 0);

begin

    ------------------------------------------------------------------
    -- Instancia o somador
    ------------------------------------------------------------------
    uut : entity work.fp_adder
        port map(
            sign1   => sign1,
            sign2   => sign2,
            exp1    => exp1,
            exp2    => exp2,
            frac1   => frac1,
            frac2   => frac2,
            sign_out=> sign_out,
            exp_out => exp_out,
            frac_out=> frac_out
        );

    ------------------------------------------------------------------
    -- Casos de teste
    ------------------------------------------------------------------
    process
    begin

        ------------------------------------------------------------------
        -- Caso 1
        ------------------------------------------------------------------
        sign1 <= '0';
        exp1  <= "1000";
        frac1 <= "11010101";

        sign2 <= '0';
        exp2  <= "1000";
        frac2 <= "10110000";

        wait for 100 ns;

        ------------------------------------------------------------------
        -- Caso 2
        ------------------------------------------------------------------
        sign1 <= '0';
        exp1  <= "0111";
        frac1 <= "11110000";

        sign2 <= '1';
        exp2  <= "0111";
        frac2 <= "10100000";

        wait for 100 ns;

        ------------------------------------------------------------------
        -- Caso 3
        ------------------------------------------------------------------
        sign1 <= '1';
        exp1  <= "1010";
        frac1 <= "11111111";

        sign2 <= '0';
        exp2  <= "1000";
        frac2 <= "10000000";

        wait for 100 ns;

        ------------------------------------------------------------------
        -- Caso 4
        ------------------------------------------------------------------
        sign1 <= '0';
        exp1  <= "0011";
        frac1 <= "10000000";

        sign2 <= '0';
        exp2  <= "0010";
        frac2 <= "10000000";

        wait for 100 ns;

        ------------------------------------------------------------------
        -- Finaliza
        ------------------------------------------------------------------
        wait;

    end process;

end sim;
